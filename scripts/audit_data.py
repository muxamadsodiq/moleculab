"""Audit every seed evidence record against its source text; write reports_audit/DATA_QUALITY_AUDIT.md.

    python -m scripts.audit_data

Offline: uses data/seed/pubmed_cache.json (fetched from PubMed) and enriched.json
(GBIF/PubChem/Crossref results). Records are classified, never deleted.
"""
import json
import re
import sys
from collections import Counter
from pathlib import Path

from app.textnorm import excerpt_in_source, fold

ROOT = Path(__file__).resolve().parent.parent
SEED = ROOT / "data" / "seed"
OUT = ROOT / "reports_audit" / "DATA_QUALITY_AUDIT.md"

VERIFIED, REVIEW, CORRECTION, UNSUPPORTED = ("Verified against source text", "Requires scientific review",
                                             "Requires correction", "Unsupported")
CATEGORY_CUES = {
    "direct_experimental_identification": r"isolat|identif|nmr|hplc|gc[-/ ]?ms|lc[-/ ]?ms|ms\b|quantif|analys|"
                                          r"profil|constituent|compound|yield|detect|revealed|dominat",
    "tentative_identification": r"assign|detect|tentativ|profil|identif|co-presence",
    "secondary_source_report": r".",
    "computational_prediction": r"docking|in silico|simulat|computational|predict",
    "traditional_use": r"tradition|folk|ethno|tea",
}


def _abbrev(name: str) -> str:
    genus, _, species = name.partition(" ")
    return f"{genus[0]}. {species}"


def audit() -> list[dict]:
    ev = json.loads((SEED / "evidence.json").read_text(encoding="utf-8"))["records"]
    cache = {c["pmid"]: c for c in json.loads((SEED / "pubmed_cache.json").read_text(encoding="utf-8"))}
    enriched = json.loads((SEED / "enriched.json").read_text(encoding="utf-8"))
    rows = []
    for i, r in enumerate(ev, start=1):
        issues, notes = [], []
        pub = cache.get(r["pmid"])
        cr = enriched["publications"].get(r["pmid"], {})
        if not pub or not pub.get("title"):
            rows.append({**r, "n": i, "classification": UNSUPPORTED, "issues": ["publication not in cache"],
                         "notes": []})
            continue
        if not cr.get("crossref_ok"):
            notes.append("DOI not confirmed by Crossref")
        source = f"{pub['title']} {pub['abstract']}"
        if not excerpt_in_source(r["original_excerpt"], pub["title"], pub["abstract"]):
            rows.append({**r, "n": i, "classification": UNSUPPORTED, "issues": ["excerpt not found in source text"],
                         "notes": notes})
            continue
        ex = fold(r["original_excerpt"])
        if r["compound"]:
            comp = enriched["compounds"].get(r["compound"], {})
            names = {fold(r["compound"])} | {fold(s) for s in comp.get("synonyms", [])}
            if not any(n in ex for n in names if len(n) >= 4):
                issues.append(f"excerpt does not name the compound '{r['compound']}'")
            if not comp.get("ok"):
                notes.append("compound has no PubChem identifier")
        plant = r["plant"]
        plant_named = any(k in fold(source) for k in (fold(plant), fold(_abbrev(plant))))
        if not plant_named:
            issues.append("plant name not found in title/abstract")
        g = enriched["plants"].get(plant, {})
        if not (g.get("ok") and g.get("match_type") == "EXACT" and g.get("status") == "ACCEPTED"):
            issues.append(f"plant identity ambiguous in GBIF (match {g.get('match_type')}, status {g.get('status')})")
        cue = CATEGORY_CUES.get(r["evidence_type"])
        if cue and not re.search(cue, f"{r['original_excerpt']} {r.get('identification_method') or ''}", re.I):
            issues.append(f"excerpt/method gives no cue for category {r['evidence_type']}")
        if r.get("curator_notes"):
            notes.append(f"curator note: {r['curator_notes']}")
        if r["evidence_type"] in ("tentative_identification", "secondary_source_report", "computational_prediction"):
            notes.append(f"weaker evidence category ({r['evidence_type']})")
        if (r.get("identification_method") or "").lower().startswith(("not described", "isolation (method not")):
            notes.append("method not described in abstract")
        if not fold(plant) in fold(r["original_excerpt"]) and r["compound"]:
            notes.append("plant named in title/abstract but not in the excerpt itself")
        cls = CORRECTION if issues else REVIEW if any(not n.startswith("plant named") for n in notes) else VERIFIED
        rows.append({**r, "n": i, "classification": cls, "issues": issues, "notes": notes})
    return rows


def write(rows: list[dict]) -> None:
    counts = Counter(r["classification"] for r in rows)
    lines = [
        "# Data-quality audit of the seed corpus",
        "",
        "Generated by `python -m scripts.audit_data` from `data/seed/` (offline: cached PubMed text plus the "
        "GBIF/PubChem/Crossref results in `enriched.json`). No record was deleted or changed by this audit.",
        "",
        "**No record has been reviewed by a domain expert.** \"Verified against source text\" means only that:",
        "",
        "- the publication exists;",
        "- the excerpt occurs verbatim in its title or abstract;",
        "- the excerpt names the compound;",
        "- the plant name is unambiguous in GBIF;",
        "- the excerpt or method is consistent with the assigned evidence category.",
        "",
        "| Classification | Records |",
        "|---|---|",
        *[f"| {c} | {counts.get(c, 0)} |" for c in (VERIFIED, REVIEW, CORRECTION, UNSUPPORTED)],
        "",
        "## Per-record results",
        "",
        "| # | Plant | Compound | Type | PMID | Classification | Issues / notes |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        detail = "; ".join([f"**{x}**" for x in r["issues"]] + r["notes"]) or "—"
        lines.append(f"| {r['n']} | {r['plant']} | {r['compound'] or '(plant-level)'} | {r['evidence_type']} | "
                     f"{r['pmid']} | {r['classification']} | {detail} |")
    corr = [r for r in rows if r["classification"] == CORRECTION]
    lines += ["", "## Records requiring correction", ""]
    lines += [f"- Record {r['n']} ({r['plant']} / {r['compound']}, PMID {r['pmid']}): {'; '.join(r['issues'])}."
              for r in corr] or ["None."]
    lines += ["", "## Corpus-level findings", "",
              "- All 20 publications exist in PubMed and all 20 DOIs resolved in Crossref "
              "(`enriched.json`, retrieved 2026-11-16).",
              "- All 5 plant names matched GBIF exactly with status ACCEPTED.",
              "- 22 of 23 compound names resolved in PubChem; `8-acetoxy-5-hydroxyumbelliprenin` did not.",
              "- Russian and Uzbek vernacular names (8 entries) have no cited source.",
              "- Curation was AI-assisted from abstracts only; full texts were not read.", ""]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")  # Windows consoles default to a legacy code page
    rows = audit()
    write(rows)
    print(Counter(r["classification"] for r in rows), "->", OUT)
    for r in rows:
        if r["issues"]:
            print(r["n"], r["plant"], r["compound"], r["issues"])

"""Live check of every external integration; writes reports_audit/V03_INTEGRATIONS.md.

    python -m scripts.check_integrations

Real network requests only (no mocks). For each source: a known-good request with response validation,
a known-missing record, and a forced timeout (1 ms) to confirm failures are reported, not raised.
"""
import sys
from datetime import datetime, timezone
from pathlib import Path

from app.clients.crossref import CrossrefClient
from app.clients.gbif import GBIFClient
from app.clients.pubchem import PubChemClient
from app.clients.pubmed import PubMedClient

OUT = Path(__file__).resolve().parent.parent / "reports_audit" / "V03_INTEGRATIONS.md"


def run() -> list[dict]:
    rows = []

    def add(source, case, res, valid: bool | None, expect_ok: bool):
        passed = (res.ok == expect_ok) and (valid is not False)
        rows.append({"source": source, "case": case, "url": res.request_url, "status": res.status_code,
                     "ok": res.ok, "error": res.error, "valid": valid, "ms": res.elapsed_ms,
                     "at": res.retrieved_at, "pass": passed})

    r = PubChemClient().search_name("glabridin")
    add("PubChem", "name → properties", r, bool(r.ok and r.data[0]["pubchem_cid"] == 124052
                                                and r.data[0]["molecular_formula"] == "C20H20O4"), True)
    add("PubChem", "missing record", PubChemClient().search_name("zzqx-not-a-compound-name"), None, False)
    add("PubChem", "timeout 1 ms", PubChemClient(timeout=0.001, max_retries=0).search_name("glabridin"), None, False)

    r = PubMedClient().fetch(["38667552"])
    add("PubMed", "efetch PMID 38667552", r, bool(r.ok and r.data and "Glycyrrhiza glabra" in r.data[0]["title"]
                                                  and r.data[0]["doi"] == "10.3390/jfb15040095"), True)
    r = PubMedClient().search('"Glycyrrhiza glabra"[tiab] AND glabridin[tiab]', 3)
    add("PubMed", "esearch", r, bool(r.ok and r.data["count"] > 0), True)
    r = PubMedClient().fetch(["999999999"])
    add("PubMed", "missing PMID", r, bool(r.ok and r.data == []), True)
    add("PubMed", "timeout 1 ms", PubMedClient(timeout=0.001, max_retries=0).search("glabridin"), None, False)

    r = CrossrefClient().get_doi("10.3390/jfb15040095")
    add("Crossref", "DOI 10.3390/jfb15040095", r, bool(r.ok and "Liquiritin" in r.data["title"] and r.data["year"] == 2024), True)
    add("Crossref", "missing DOI", CrossrefClient().get_doi("10.9999/moleculab-does-not-exist"), None, False)
    add("Crossref", "timeout 1 ms", CrossrefClient(timeout=0.001, max_retries=0).get_doi("10.3390/jfb15040095"), None, False)

    r = GBIFClient().match("Glycyrrhiza glabra")
    add("GBIF", "species match", r, bool(r.ok and r.data["family"] == "Fabaceae" and r.data["status"] == "ACCEPTED"), True)
    add("GBIF", "no match", GBIFClient().match("Zzqx nonexistentia"), None, False)
    add("GBIF", "timeout 1 ms", GBIFClient(timeout=0.001, max_retries=0).match("Glycyrrhiza glabra"), None, False)
    return rows


def write(rows: list[dict]) -> None:
    lines = [f"# Live integration check — {datetime.now(timezone.utc).isoformat(timespec='seconds')}", "",
             "Generated by `python -m scripts.check_integrations`. Every row is a real network request.", "",
             "| Source | Case | HTTP | ok | Response valid | Time (ms) | Error | Result | Request URL |",
             "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        valid = "—" if r["valid"] is None else ("yes" if r["valid"] else "**no**")
        lines.append(f"| {r['source']} | {r['case']} | {r['status'] or '—'} | {r['ok']} | {valid} | {r['ms']} | "
                     f"{(r['error'] or '').replace('|', '/')[:60]} | {'PASS' if r['pass'] else '**FAIL**'} | "
                     f"`{(r['url'] or '')[:90]}` |")
    lines += ["", "Rate limiting (HTTP 429) and malformed JSON cannot be triggered safely against the live services; "
              "they are covered by mocked-transport tests in `tests/test_clients.py` and are NOT claimed as live results."]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")  # Windows consoles default to a legacy code page
    rows = run()
    write(rows)
    for r in rows:
        print(f"{'PASS' if r['pass'] else 'FAIL'} {r['source']:8} {r['case']:24} HTTP {r['status']} ok={r['ok']} "
              f"valid={r['valid']} {r['ms']}ms {r['error'] or ''}")
